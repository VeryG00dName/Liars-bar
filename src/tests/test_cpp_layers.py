"""
Test C++ layer implementations against PyTorch reference outputs.

This script loads reference outputs generated by generate_pytorch_reference.py
and compares them against C++ layer-by-layer implementations.
"""

from __future__ import annotations

import argparse
import pickle
from pathlib import Path
from typing import Dict

import torch
import numpy as np

from src.misc import lb


def load_reference(path: Path) -> Dict[str, torch.Tensor]:
    """Load reference outputs from pickle file."""
    with open(path, 'rb') as f:
        return pickle.load(f)


def load_checkpoint_weights(checkpoint_path: Path, agent_key: str = 'self') -> Dict[str, torch.Tensor]:
    """Load model weights from checkpoint."""
    checkpoint = torch.load(checkpoint_path, map_location='cpu')

    if 'policy_nets' in checkpoint and agent_key in checkpoint['policy_nets']:
        return checkpoint['policy_nets'][agent_key]
    elif 'model_state_dict' in checkpoint:
        return checkpoint['model_state_dict']
    else:
        raise ValueError(f"Could not find model state dict in checkpoint (keys: {list(checkpoint.keys())})")


def pad_model_weights(model_state_dict: Dict[str, torch.Tensor], pad_obs_to: int = 16) -> Dict[str, torch.Tensor]:
    """
    Pad observation encoder weights for CUDA alignment.

    Args:
        model_state_dict: Model state dictionary
        pad_obs_to: Target dimension for padding (default 16)

    Returns:
        Modified state dict with padded weights
    """
    # Pad obs_encoder.0.weight from [hidden_dim, obs_dim] to [hidden_dim, pad_obs_to]
    obs_linear_weight_key = "obs_encoder.0.weight"
    if obs_linear_weight_key in model_state_dict:
        weight = model_state_dict[obs_linear_weight_key]
        hidden_dim, obs_dim = weight.shape

        if obs_dim < pad_obs_to:
            # Pad with zeros
            padding = torch.zeros(hidden_dim, pad_obs_to - obs_dim, dtype=weight.dtype, device=weight.device)
            padded_weight = torch.cat([weight, padding], dim=1)
            model_state_dict[obs_linear_weight_key] = padded_weight
            print(f"Padded {obs_linear_weight_key} from [{hidden_dim}, {obs_dim}] to [{hidden_dim}, {pad_obs_to}]")

    return model_state_dict


def prepare_batched_weights(
    state_dict: Dict[str, torch.Tensor],
    num_layers: int = 2,
    num_experts: int = 8,
    device: str = 'cpu'
) -> Dict[str, torch.Tensor]:
    """
    Prepare batched weights for C++ testing.

    For single-policy testing, we add a batch dimension to all weights.
    Also pre-stacks MoE expert weights and creates pointer tensors.
    """
    # First, prestack MoE expert weights (must be done before adding batch dim)
    print(f"Pre-stacking MoE expert weights ({num_layers} layers, {num_experts} experts)...")
    state_dict_stacked = lb.prestack_moe_expert_weights(state_dict, num_layers, num_experts)

    batched = {}

    for key, value in state_dict_stacked.items():
        # Add batch dimension [1, ...]
        batched[key] = value.unsqueeze(0).to(device)

    # Create MoE weight pointers (must be done after moving to device)
    print("Creating MoE weight pointers...")
    batched_with_ptrs = lb.create_moe_weight_pointers(batched, num_layers, num_experts)

    # Add fixed buffers (action decomposition LUTs)
    batched_final = lb.add_fixed_buffers(batched_with_ptrs, device)

    return batched_final


def compare_tensors(
    name: str,
    cpp_output: torch.Tensor,
    pytorch_output: torch.Tensor,
    rtol: float = 1e-3,
    atol: float = 1e-4
) -> bool:
    """
    Compare two tensors and report statistics.

    Returns:
        True if tensors match within tolerance, False otherwise
    """
    # Move to CPU and convert to float32 for comparison
    cpp_np = cpp_output.detach().cpu().float().numpy()
    pytorch_np = pytorch_output.detach().cpu().float().numpy()

    # Check shapes
    if cpp_np.shape != pytorch_np.shape:
        print(f"[FAIL] {name}: Shape mismatch! C++: {cpp_np.shape}, PyTorch: {pytorch_np.shape}")
        return False

    # Compute errors
    abs_diff = np.abs(cpp_np - pytorch_np)
    rel_diff = abs_diff / (np.abs(pytorch_np) + 1e-8)

    max_abs_error = np.max(abs_diff)
    mean_abs_error = np.mean(abs_diff)
    max_rel_error = np.max(rel_diff)
    mean_rel_error = np.mean(rel_diff)

    # Check if within tolerance
    matches = np.allclose(cpp_np, pytorch_np, rtol=rtol, atol=atol)

    status = "PASS" if matches else "FAIL"
    print(f"[{status}] {name}:")
    print(f"  Shape: {cpp_np.shape}")
    print(f"  Max abs error: {max_abs_error:.6e}")
    print(f"  Mean abs error: {mean_abs_error:.6e}")
    print(f"  Max rel error: {max_rel_error:.6e}")
    print(f"  Mean rel error: {mean_rel_error:.6e}")

    if not matches:
        # Print some mismatched values
        mismatch_mask = abs_diff > (atol + rtol * np.abs(pytorch_np))
        mismatch_indices = np.where(mismatch_mask)
        num_mismatches = len(mismatch_indices[0])
        print(f"  Number of mismatches: {num_mismatches} / {cpp_np.size} ({100 * num_mismatches / cpp_np.size:.2f}%)")

        if num_mismatches > 0:
            # Show first few mismatches
            num_show = min(5, num_mismatches)
            print(f"  First {num_show} mismatches:")
            for i in range(num_show):
                idx = tuple(ind[i] for ind in mismatch_indices)
                print(f"    [{idx}] C++: {cpp_np[idx]:.6f}, PyTorch: {pytorch_np[idx]:.6f}, Diff: {abs_diff[idx]:.6e}")

    return matches


def test_action_decomposition(
    reference: Dict[str, torch.Tensor],
    batched_weights: Dict[str, torch.Tensor],
    device: str = 'cpu'
) -> bool:
    """Test action decomposition layer."""
    print("\n" + "=" * 80)
    print("Testing Action Decomposition")
    print("=" * 80)

    # Get inputs from reference
    action_sequence = reference['input/action_sequence'].to(device)
    padding_mask = reference.get('input/padding_mask')
    if padding_mask is not None:
        padding_mask = padding_mask.to(device)

    # Policy indices (single policy, index 0)
    batch_size = action_sequence.size(0)
    policy_indices = torch.zeros(batch_size, dtype=torch.long, device=device)

    # Call C++ function
    act_kind_ids_cpp, count_ids_cpp, table_flag_ids_cpp = lb.test_action_decomposition(
        action_sequence,
        batched_weights,
        policy_indices,
        padding_mask,
        count_pad=4,
        tflag_pad=3
    )

    # Compare outputs
    all_match = True
    all_match &= compare_tensors("act_kind_ids", act_kind_ids_cpp, reference['decompose/act_kind_ids'])
    all_match &= compare_tensors("count_ids", count_ids_cpp, reference['decompose/count_ids'])
    all_match &= compare_tensors("table_flag_ids", table_flag_ids_cpp, reference['decompose/table_flag_ids'])

    return all_match


def test_embeddings(
    reference: Dict[str, torch.Tensor],
    batched_weights: Dict[str, torch.Tensor],
    device: str = 'cpu'
) -> bool:
    """Test embedding layer."""
    print("\n" + "=" * 80)
    print("Testing Embeddings")
    print("=" * 80)

    # Get inputs
    obs_sequence = reference['input/obs_sequence'].to(device)
    act_kind_ids = reference['decompose/act_kind_ids'].to(device)
    count_ids = reference['decompose/count_ids'].to(device)
    table_flag_ids = reference['decompose/table_flag_ids'].to(device)
    agent_types = reference['input/agent_types'].to(device)
    positions = reference['input/positions'].to(device)

    batch_size = obs_sequence.size(0)
    policy_indices = torch.zeros(batch_size, dtype=torch.long, device=device)

    # Call C++ function
    embeddings_cpp = lb.test_embeddings(
        obs_sequence,
        act_kind_ids,
        count_ids,
        table_flag_ids,
        agent_types,
        positions,
        batched_weights,
        policy_indices
    )

    # Compare outputs
    all_match = True
    # Test obs_encoder intermediate outputs first
    for key in ['obs_linear', 'obs_layernorm', 'obs_embed']:
        all_match &= compare_tensors(key, embeddings_cpp[key], reference[f'embeddings/{key}'])

    # Then test other embeddings
    for key in ['act_kind_embed', 'count_embed', 'table_flag_embed',
                'action_embed', 'agent_embed', 'position_embed']:
        all_match &= compare_tensors(key, embeddings_cpp[key], reference[f'embeddings/{key}'])

    return all_match


