def test_fusion(
    reference: Dict[str, torch.Tensor],
    device: str = 'cpu',
    hidden_dim: int = 256
) -> bool:
    """Test fusion layer."""
    print("\n" + "=" * 80)
    print("Testing Fusion")
    print("=" * 80)

    # Get inputs
    g_obs = reference['gating/g_obs'].to(device)
    g_action = reference['gating/g_action'].to(device)
    g_agent = reference['gating/g_agent'].to(device)
    g_position = reference['gating/g_position'].to(device)
    obs_embed = reference['embeddings/obs_embed'].to(device)
    action_embed = reference['embeddings/action_embed'].to(device)
    agent_embed = reference['embeddings/agent_embed'].to(device)
    position_embed = reference['embeddings/position_embed'].to(device)

    # Call C++ function
    fusion_cpp = lb.test_fusion(
        g_obs, g_action, g_agent, g_position,
        obs_embed, action_embed, agent_embed, position_embed,
        hidden_dim
    )

    # Compare outputs
    all_match = True
    all_match &= compare_tensors("fused_raw", fusion_cpp['fused_raw'], reference['fusion/fused_raw'])
    all_match &= compare_tensors("combined", fusion_cpp['combined'], reference['fusion/combined'])

    return all_match


def test_transformer_layers(
    reference: Dict[str, torch.Tensor],
    batched_weights: Dict[str, torch.Tensor],
    num_layers: int = 2,
    num_heads: int = 4,
    num_experts: int = 8,
    top_k: int = 2,
    hidden_dim: int = 256,
    device: str = 'cpu'
) -> bool:
    """Test all transformer layers (attention + MoE)."""
    print("\n" + "=" * 80)
    print("Testing Transformer Layers")
    print("=" * 80)

    all_match = True

    # Start with fusion output
    x_cpp = reference['fusion/combined'].to(device)

    batch_size = x_cpp.size(0)
    policy_indices = torch.zeros(batch_size, dtype=torch.long, device=device)
    padding_mask = reference.get('input/padding_mask')
    if padding_mask is not None:
        padding_mask = padding_mask.to(device)

    for layer_idx in range(num_layers):
        print(f"\n--- Layer {layer_idx} ---")

        # Test attention
        print(f"\nAttention Layer {layer_idx}:")
        attn_cpp = lb.test_attention_layer(
            x_cpp,
            batched_weights,
            policy_indices,
            padding_mask,
            layer_idx,
            num_heads,
            hidden_dim
        )

        all_match &= compare_tensors(
            f"layer_{layer_idx}/attn_output",
            attn_cpp['attn_output'],
            reference[f'transformer/layer_{layer_idx}/attn_output']
        )
        all_match &= compare_tensors(
            f"layer_{layer_idx}/post_attn",
            attn_cpp['post_attn'],
            reference[f'transformer/layer_{layer_idx}/post_attn']
        )

        # Use post_attn output for MoE input
        x_cpp = attn_cpp['post_attn']

        # Test MoE
        print(f"\nMoE Layer {layer_idx}:")
        moe_cpp = lb.test_moe_layer(
            x_cpp,
            batched_weights,
            policy_indices,
            layer_idx,
            num_experts,
            top_k,
            hidden_dim
        )

        all_match &= compare_tensors(
            f"layer_{layer_idx}/moe_gate_logits",
            moe_cpp['gate_logits'],
            reference[f'transformer/layer_{layer_idx}/moe_gate_logits']
        )
        all_match &= compare_tensors(
            f"layer_{layer_idx}/moe_topk_indices",
            moe_cpp['topk_indices'],
            reference[f'transformer/layer_{layer_idx}/moe_topk_indices']
        )
        all_match &= compare_tensors(
            f"layer_{layer_idx}/moe_topk_scores",
            moe_cpp['topk_scores'],
            reference[f'transformer/layer_{layer_idx}/moe_topk_scores']
        )
        all_match &= compare_tensors(
            f"layer_{layer_idx}/moe_output",
            moe_cpp['moe_output'],
            reference[f'transformer/layer_{layer_idx}/moe_output']
        )

        # Residual + norm for next layer
        # Note: C++ test function doesn't include this, so we need to do it here
        x_cpp = x_cpp + moe_cpp['moe_output']
        # Apply layer norm manually - but we'd need the weights
        # For now, use reference output to continue
        x_cpp = reference[f'transformer/layer_{layer_idx}/output'].to(device)

    # Test final norm (uses reference since we're chaining layers)
    transformer_output_ref = reference['transformer/final_output'].to(device)

    # For now, just verify we can proceed to heads
    print("\nFinal transformer output ready for heads")

    return all_match


def test_heads(
    reference: Dict[str, torch.Tensor],
    batched_weights: Dict[str, torch.Tensor],
    num_experts: int = 8,
    device: str = 'cpu'
) -> bool:
    """Test head layers."""
    print("\n" + "=" * 80)
    print("Testing Heads")
    print("=" * 80)

    # Get transformer output
    transformer_output = reference['transformer/final_output'].to(device)

    batch_size = transformer_output.size(0)
    policy_indices = torch.zeros(batch_size, dtype=torch.long, device=device)

    # Call C++ function
    heads_cpp = lb.test_heads(
        transformer_output,
        batched_weights,
        policy_indices,
        num_experts
    )

    # Compare outputs
    all_match = True
    all_match &= compare_tensors("action_heads_stacked", heads_cpp['action_heads_stacked'], reference['heads/action_heads_stacked'])
    all_match &= compare_tensors("opp_heads_stacked", heads_cpp['opp_heads_stacked'], reference['heads/opp_heads_stacked'])
    all_match &= compare_tensors("reward_heads_stacked", heads_cpp['reward_heads_stacked'], reference['heads/reward_heads_stacked'])
    all_match &= compare_tensors("win_heads_stacked", heads_cpp['win_heads_stacked'], reference['heads/win_heads_stacked'])

    return all_match


def main():
    parser = argparse.ArgumentParser(description='Test C++ layers against PyTorch reference')
    parser.add_argument('reference', type=str, help='Path to reference outputs pickle file')
    parser.add_argument('checkpoint', type=str, help='Path to checkpoint')
    parser.add_argument('--agent-key', type=str, default='self', help='Agent key in checkpoint')
    parser.add_argument('--device', type=str, default='cpu', help='Device to use (cpu or cuda)')

    args = parser.parse_args()

    print("=" * 80)
    print("C++ Layer Testing Framework")
    print("=" * 80)
    print(f"Reference: {args.reference}")
    print(f"Checkpoint: {args.checkpoint}")
    print(f"Device: {args.device}")
    print()

    # Load reference outputs
    print("Loading reference outputs...")
    reference = load_reference(Path(args.reference))
    print(f"Loaded {len(reference)} tensors")

    # Load checkpoint weights
    print("Loading checkpoint weights...")
    state_dict = load_checkpoint_weights(Path(args.checkpoint), args.agent_key)
    print(f"Loaded {len(state_dict)} weight tensors")

    # Pad model weights for CUDA alignment
    PAD_OBS_TO = 16
    print(f"Padding model weights for CUDA alignment (obs_dim -> {PAD_OBS_TO})...")
    state_dict = pad_model_weights(state_dict, pad_obs_to=PAD_OBS_TO)

    # Prepare batched weights for C++ (includes MoE expert weight stacking)
    print("Preparing batched weights...")
    batched_weights = prepare_batched_weights(
        state_dict,
        num_layers=2,
        num_experts=8,
        device=args.device
    )
    print(f"Prepared {len(batched_weights)} batched weights")

    # Run tests
    results = {}

    results['action_decomposition'] = test_action_decomposition(reference, batched_weights, args.device)
    results['embeddings'] = test_embeddings(reference, batched_weights, args.device)
    results['gating'] = test_gating(reference, batched_weights, args.device)
    results['fusion'] = test_fusion(reference, args.device)
    results['transformer'] = test_transformer_layers(reference, batched_weights, device=args.device)
    results['heads'] = test_heads(reference, batched_weights, device=args.device)

    # Summary
    print("\n" + "=" * 80)
    print("SUMMARY")
    print("=" * 80)

    for test_name, passed in results.items():
        status = "PASS" if passed else "FAIL"
        print(f"{test_name:30s}: {status}")

    all_passed = all(results.values())
    print()
    if all_passed:
        print("All tests PASSED!")
        return 0
    else:
        print("Some tests FAILED!")
        return 1


if __name__ == '__main__':
    exit(main())
